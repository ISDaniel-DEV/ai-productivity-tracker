-- Compatible tanto con una base vacía como con el esquema inicial observado.
CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), email VARCHAR(254) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL, password_hash VARCHAR(255) NOT NULL
);
CREATE TABLE IF NOT EXISTS goal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period VARCHAR(10) NOT NULL, status VARCHAR(20) NOT NULL,
    description TEXT, end_date DATE NOT NULL, start_date DATE NOT NULL,
    title VARCHAR(150) NOT NULL, user_id BIGINT NOT NULL REFERENCES app_user(id)
);
CREATE TABLE IF NOT EXISTS task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    completed_at TIMESTAMPTZ, description TEXT, due_date DATE,
    status VARCHAR(20) NOT NULL, title VARCHAR(150) NOT NULL,
    goal_id BIGINT NOT NULL REFERENCES goal(id)
);
