CREATE TABLE note_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    type VARCHAR(10) NOT NULL CHECK (type IN ('topic','project')),
    name VARCHAR(80) NOT NULL, normalized_name VARCHAR(80) NOT NULL,
    UNIQUE (user_id, type, normalized_name), UNIQUE (id, user_id)
);
CREATE TABLE notebook_note (
    id UUID PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES app_user(id),
    category_id BIGINT, kind VARCHAR(10) NOT NULL CHECK (kind IN ('note','idea')),
    title VARCHAR(180) NOT NULL, body TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(), request_key VARCHAR(36),
    FOREIGN KEY (category_id, user_id) REFERENCES note_category(id, user_id),
    UNIQUE (user_id, request_key)
);
CREATE INDEX note_owner_created ON notebook_note(user_id, created_at DESC);
CREATE INDEX note_owner_category ON notebook_note(user_id, category_id);
CREATE TABLE notebook_import (
    user_id BIGINT NOT NULL REFERENCES app_user(id), import_key VARCHAR(64) NOT NULL,
    payload_hash VARCHAR(64) NOT NULL, imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    task_count INTEGER NOT NULL, goal_count INTEGER NOT NULL, note_count INTEGER NOT NULL,
    PRIMARY KEY (user_id, import_key)
);
